#!/usr/bin/env node
// Builds momondo-save.user.js from three sources:
//   ../skills/momondo-search/scripts/momondo_crawler.js  (the parser the browser workers use)
//   momondo-save.core.js  (rows, self-check, inbox file, issue links)
//   momondo-save.ui.js    (buttons, page reading, GitHub calls)
// Usage: node plugin/userscripts/build.js          writes the userscript
//        node plugin/userscripts/build.js --check  exits 1 if the userscript is out of date
'use strict';
const fs = require('fs');
const path = require('path');

const SCRIPT_VERSION = '1.0';
const DIR = __dirname;
const OUT = path.join(DIR, 'momondo-save.user.js');
const CRAWLER = path.join(DIR, '..', 'skills', 'momondo-search', 'scripts', 'momondo_crawler.js');
const RAW = 'https://raw.githubusercontent.com/Olafcito/latam-trip/main/plugin/userscripts/momondo-save.user.js';

const read = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n').replace(/\n*$/, '\n');

function parserVersion(src) {
  const m = /window\.PARSER_VERSION='([^']+)'/.exec(src);
  if (!m) throw new Error('PARSER_VERSION not found in momondo_crawler.js');
  return m[1];
}

function build() {
  const crawler = read(CRAWLER);
  const core = read(path.join(DIR, 'momondo-save.core.js'));
  const ui = read(path.join(DIR, 'momondo-save.ui.js'));
  const version = SCRIPT_VERSION + '.' + parserVersion(crawler);
  return [
    '// ==UserScript==',
    '// @name         Momondo save (latam-trip)',
    '// @namespace    https://github.com/Olafcito/latam-trip',
    '// @version      ' + version,
    '// @description  Save Momondo prices or one opened trip into the latam-trip repo',
    '// @match        https://www.momondo.dk/flight-search/*',
    '// @match        https://momondo.dk/flight-search/*',
    '// @grant        GM_getValue',
    '// @grant        GM_setValue',
    '// @grant        GM_deleteValue',
    '// @grant        GM_registerMenuCommand',
    '// @grant        GM_xmlhttpRequest',
    '// @grant        GM_setClipboard',
    '// @grant        GM_openInTab',
    '// @connect      api.github.com',
    '// @run-at       document-idle',
    '// @noframes',
    '// @updateURL    ' + RAW,
    '// @downloadURL  ' + RAW,
    '// ==/UserScript==',
    '',
    '// GENERATED by plugin/userscripts/build.js. Do not edit this file.',
    '// Edit momondo_crawler.js, momondo-save.core.js or momondo-save.ui.js and run node plugin/userscripts/build.js.',
    '(function () {',
    '// The crawler runs in its own scope with a private window object, so nothing leaks into the page.',
    'var CR = (function () {',
    'var window = {};',
    'function parseDlg(t, d) { return window.parseDlg(t, d); }',
    'function crawl(s, e, d) { return window.crawl(s, e, d); }',
    'function lines(r, m, n) { return window.lines(r, m, n); }',
    '// BEGIN plugin/skills/momondo-search/scripts/momondo_crawler.js',
    crawler + '// END momondo_crawler.js',
    'return window;',
    '})();',
    '// BEGIN plugin/userscripts/momondo-save.core.js',
    core + '// END momondo-save.core.js',
    '// BEGIN plugin/userscripts/momondo-save.ui.js',
    ui + '// END momondo-save.ui.js',
    '})();',
    ''
  ].join('\n');
}

function isCurrent() {
  if (!fs.existsSync(OUT)) return false;
  return fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') === build();
}

module.exports = { build, isCurrent, OUT, CRAWLER, parserVersion };

if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (isCurrent()) { console.log('momondo-save.user.js is up to date'); process.exit(0); }
    console.error('momondo-save.user.js is out of date: run node plugin/userscripts/build.js');
    process.exit(1);
  }
  fs.writeFileSync(OUT, build());
  console.log('wrote ' + path.relative(process.cwd(), OUT));
}
