-- Every table of spec 4.1 and 4.2. A field with no column goes to extra.

create table public.airports (
  code text primary key,
  name text, city text, country text, lat double precision, lon double precision,
  extra jsonb not null default '{}'
);

create table public.places (
  id text primary key,
  seq bigint generated by default as identity unique,
  airport_code text references public.airports (code),
  name text, country text, lat double precision, lon double precision, type text,
  popularity int, why text, source text, origin text,
  extra jsonb not null default '{}'
);
create index places_airport_code_idx on public.places (airport_code);

create table public.connections (
  id bigint generated by default as identity primary key,
  from_id text not null references public.places (id),
  to_id text not null references public.places (id),
  mode text not null,
  operator text,
  duration_h numeric, price_dkk numeric, frequency text, overnight boolean, border boolean, both_ways boolean,
  source text, source_year int, notes text, origin text, duration_range text, price_range_local text,
  extra jsonb not null default '{}',
  unique nulls not distinct (from_id, to_id, mode, operator)
);
create index connections_from_idx on public.connections (from_id);
create index connections_to_idx on public.connections (to_id);

create table public.profiles (
  place_id text not null references public.places (id),
  kind text not null,
  seq bigint generated by default as identity unique,
  checked_at date, tagline text, summary text, touristy int, origin text,
  image jsonb, things_to_do jsonb, hostels jsonb, sources jsonb,
  extra jsonb not null default '{}',
  primary key (place_id, kind)
);

create table public.place_images (
  place_id text primary key references public.places (id),
  seq bigint generated by default as identity unique,
  origin text,
  image jsonb,
  extra jsonb not null default '{}'
);

create table public.experiences (
  id text primary key,
  seq bigint generated by default as identity unique,
  name text, category text, country text, lat double precision, lon double precision, area text, summary text,
  season text, dec_jan text, price numeric, price_dkk numeric, duration text, requirements text,
  researched boolean, checked_at date, tags text[], places text[],
  details jsonb, sources jsonb,
  extra jsonb not null default '{}'
);

create table public.experience_images (
  id text primary key,
  seq bigint generated by default as identity unique,
  image jsonb,
  extra jsonb not null default '{}'
);

create table public.stays (
  id bigint generated by default as identity primary key,
  place_id text not null references public.places (id),
  site text not null, name text not null, room text not null, check_in date not null, check_out date not null,
  type text, dkk_per_night numeric, nights int, rating numeric, reviews int, url text, property_id text,
  observed_at timestamptz, task_id text, notes text,
  extra jsonb not null default '{}',
  unique (place_id, site, name, room, check_in, check_out)
);
create index stays_place_idx on public.stays (place_id);

create table public.quotes (
  seq bigint generated by default as identity primary key,
  quote_id text not null unique,
  build_qid text,
  agent text, task_id text, source text,
  structure text check (structure in ('one_way', 'return', 'open_jaw', 'multi_city')),
  first_seen timestamptz, last_seen timestamptz, seen_count int not null default 1,
  first_from text references public.airports (code), first_to text references public.airports (code),
  last_from text references public.airports (code), last_to text references public.airports (code),
  first_date date, last_date date,
  price numeric, currency text, price_dkk numeric, tickets int, self_transfer boolean, us_transit boolean,
  out_hours numeric, home_hours numeric, usable int, flags text[],
  fare_brand text, cabin_bag text, checked_bag text, changeable text, link text, notes text, trip_name text,
  legs_requested jsonb, out_leg jsonb, mid_legs jsonb, home_leg jsonb,
  extra jsonb not null default '{}'
);
create index quotes_first_idx on public.quotes (first_from, first_to, first_date);
create index quotes_last_idx on public.quotes (last_from, last_to, last_date);
create index quotes_build_qid_idx on public.quotes (build_qid);
create index quotes_first_to_idx on public.quotes (first_to);
create index quotes_last_to_idx on public.quotes (last_to);

create table public.trips (
  id text not null,
  version int not null,
  seq bigint generated by default as identity unique,
  saved_at timestamptz, saved_by text, deleted_at timestamptz,
  data jsonb not null,
  primary key (id, version)
);

create view public.trips_latest with (security_invoker = true) as
  select distinct on (t.id) t.*
  from public.trips t
  where not exists (select 1 from public.trips d where d.id = t.id and d.deleted_at is not null)
  order by t.id, t.version desc;

create table public.documents (
  name text primary key,
  version int not null default 1,
  updated_at timestamptz not null default now(),
  data jsonb not null
);

create table public.inbox (
  id bigint generated by default as identity primary key,
  file text,
  status text not null default 'new' check (status in ('new', 'added', 'rejected')),
  reason text,
  created_at timestamptz not null default now(),
  rows jsonb,
  rejected jsonb
);

create table public.tasks (
  id bigint generated by default as identity (start with 10000) primary key,
  type text,
  status text not null default 'open' check (status in ('open', 'working', 'done', 'failed')),
  title text, trip_id text, trip_version int,
  created_at timestamptz not null default now(),
  done_at timestamptz,
  result text,
  data jsonb
);

create table public.task_log (
  seq bigint generated by default as identity primary key,
  issue int, type text, done_at timestamptz, summary text,
  task jsonb, outputs jsonb,
  extra jsonb not null default '{}'
);

create table public.agent_usage (
  seq bigint generated by default as identity primary key,
  round text, agent text, model text, tool text,
  searches numeric, tokens numeric, tool_uses numeric, seconds numeric, rows numeric
);

create table public.leases (
  name text primary key,
  holder text,
  expires_at timestamptz
);

create table public.derive_state (
  id int primary key default 1 check (id = 1),
  dirty_at timestamptz, dirty_since timestamptz, built_dirty_at timestamptz, failed_dirty_at timestamptz,
  last_started timestamptz, last_finished timestamptz,
  last_error text, last_warning text, manifest_hash text, worker_version text
);
insert into public.derive_state (id) values (1);

create table public.derived_options (
  id text primary key,
  rank int, total_dkk numeric, way_in text, way_home text, build_at timestamptz,
  data jsonb
);

create table public.owners (
  user_id uuid primary key
);

create table public.inbox_tokens (
  name text primary key,
  token_hash text not null
);
